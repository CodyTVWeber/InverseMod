#!/usr/bin/env node

const fs = require("fs");
const path = require("path");
const { primesJustAbove, greedySteps, outPath } = require("./lib");

function loadWorstCase() {
  const csv = fs.readFileSync(outPath("worst-case.csv"), "utf8").trim().split("\n");
  const headers = csv[0].split(",");
  return csv.slice(1).map((line) => {
    const cols = line.split(",");
    const row = {};
    headers.forEach((h, i) => {
      row[h] = cols[i];
    });
    return row;
  });
}

function chainTrace(x, y) {
  const yB = BigInt(y);
  let r = ((BigInt(x) % yB) + yB) % yB;
  const rows = [];
  let i = 0;
  while (r !== 1n) {
    if (2n * r > yB) {
      const before = r;
      r = yB - r;
      rows.push({
        i,
        kind: "reflect",
        r: before.toString(),
        q: "",
        s: "",
        k: (yB - 1n).toString(),
        next: r.toString()
      });
      i += 1;
      continue;
    }
    const q = yB / r;
    const s = yB % r;
    const k = q + 1n;
    const next = r * k - yB;
    rows.push({
      i,
      kind: "multiply",
      r: r.toString(),
      q: q.toString(),
      s: s.toString(),
      k: k.toString(),
      next: next.toString()
    });
    r = next;
    i += 1;
  }
  return rows;
}

function geometricHypothesis(rows) {
  const muls = rows.filter((row) => row.kind === "multiply");
  if (muls.length < 3) {
    return { held: true, note: "too short to test" };
  }
  let q0 = BigInt(muls[0].q);
  let run = 1;
  let maxRun = 1;
  let geometric = true;
  for (let i = 1; i < muls.length; i++) {
    const q = BigInt(muls[i].q);
    const sPrev = BigInt(muls[i - 1].s);
    const s = BigInt(muls[i].s);
    if (q === q0) {
      run += 1;
      maxRun = Math.max(maxRun, run);
      if (s !== sPrev * (q0 + 1n) && s !== sPrev) {
        // s grows by factor q+1 when the remainder drops by s each time:
        // r' = r - s, y = q r + s, next s' = y mod r' may be s*(q+1) mod r'.
        geometric = false;
      }
    } else {
      q0 = q;
      run = 1;
    }
  }
  const sSeq = muls.map((row) => BigInt(row.s));
  let factorRun = 0;
  let factorHeld = false;
  for (let i = 1; i < sSeq.length; i++) {
    const q = BigInt(muls[i - 1].q);
    if (sSeq[i] === sSeq[i - 1] * (q + 1n)) {
      factorRun += 1;
      if (factorRun >= 2) factorHeld = true;
    } else {
      factorRun = 0;
    }
  }
  return {
    held: factorHeld || maxRun >= 3,
    maxConstantQRun: maxRun,
    geometricFactorObserved: factorHeld,
    note: factorHeld
      ? "s grows by factor q+1 on a constant-q prefix"
      : maxRun >= 3
        ? "long constant-q run, but s is not a pure geometric sequence"
        : "no long constant-q geometric run"
  };
}

function run() {
  const worst = loadWorstCase();
  const lines = [];
  lines.push("# Worst-case chain structure");
  lines.push("");
  lines.push("Generated by `experiments/worst-case-structure.js` from `out/worst-case.csv`.");
  lines.push("Hypothesis (PLAN.md A.4): worst cases are runs where `s_i` grows geometrically");
  lines.push("by factor `q_i + 1` while `q_i` stays constant (typical of `y = 2r + 1`).");
  lines.push("");

  const traces = [];
  let allHeld = true;
  for (const row of worst) {
    const y = BigInt(row.y);
    const x = BigInt(row.worst_x);
    const check = greedySteps(x, y, { reflect: true, maxWrap: 1 });
    const rows = chainTrace(x, y);
    const hyp = geometricHypothesis(rows);
    if (!hyp.held) allHeld = false;
    traces.push({ row, check, rows, hyp });
    lines.push(`## k=${row.k}, y=${row.y}, worst_x=${row.worst_x}, W=${row.worst}`);
    lines.push("");
    lines.push(`Multiply steps from harness: ${check.multiplySteps} (reflects: ${check.reflectSteps}).`);
    lines.push(`Hypothesis: ${hyp.held ? "held" : "did not hold"} — ${hyp.note}`);
    lines.push("");
    lines.push("| i | kind | r | q=floor(y/r) | s=y mod r | k | next |");
    lines.push("|---|---|---|---|---|---|---|");
    for (const step of rows) {
      lines.push(
        `| ${step.i} | ${step.kind} | ${step.r} | ${step.q} | ${step.s} | ${step.k} | ${step.next} |`
      );
    }
    lines.push("");
  }

  lines.push("## Verdict");
  lines.push("");
  lines.push(
    allHeld
      ? "The constant-q / geometric-s hypothesis held for every k in the CSV."
      : "The constant-q / geometric-s hypothesis did not hold for every k; see per-k notes above."
  );
  lines.push("");

  const mdPath = path.join(__dirname, "out", "worst-case-structure.md");
  fs.mkdirSync(path.dirname(mdPath), { recursive: true });
  fs.writeFileSync(mdPath, lines.join("\n"));
  process.stderr.write(`wrote ${mdPath}\n`);
}

run();
